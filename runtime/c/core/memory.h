#ifndef DREAM_MEMORY_H
#define DREAM_MEMORY_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// ============================================================================
// Dream 语言 GC 管理系统
// ============================================================================

// 对象类型枚举
typedef enum {
    OBJ_DYNARRAY,
    OBJ_DYNARRAY_PTR,
    OBJ_STRING,
    OBJ_DICT,
    OBJ_TUPLE,
    OBJ_UNION,
    OBJ_ENUM,
    OBJ_INTERFACE,  // 接口值的具体对象装箱（无内部指针，无需清理）
} ObjectType;

// ============================================================================
// 内存分配函数
// ============================================================================

// 分配局部对象（非原子引用计数，快速路径）
// 适用于：单线程独占的对象（80-90% 的情况）
void* gc_alloc_local(size_t size, ObjectType type);

// 分配共享对象（原子引用计数，并发安全）
// 适用于：可能跨线程共享的对象（10-20% 的情况）
void* gc_alloc_shared(size_t size, ObjectType type);

// 通用分配函数（默认使用局部分配）
void* gc_alloc(size_t size, ObjectType type);

// 接口值对象装箱与释放（编译器管理引用计数）
void* __c_interface_alloc(int64_t size);
void __c_interface_release(void* object);

// ============================================================================
// 引用计数操作
// ============================================================================

// 增加引用计数
// - 局部对象：非原子操作（快速）
// - 共享对象：原子操作（线程安全）
void gc_retain(void* object);

// 减少引用计数（可能触发对象释放）
// - 局部对象：非原子操作（快速）
// - 共享对象：原子操作（线程安全）
void gc_release(void* object);

// 判断指针是否由 Dream GC 管理。
bool gc_is_managed(const void* object);

// 仅在对象由 Dream GC 管理时调整引用计数。
void gc_retain_if_managed(void* object);
void gc_release_if_managed(void* object);

// 获取对象的引用计数（调试用）
uint32_t gc_get_ref_count(void* object);

// ============================================================================
// 对象提升机制
// ============================================================================

// 将局部对象提升为共享对象
// 使用场景：当局部对象需要跨线程传递时调用
// 注意：会递归提升容器中的所有子对象
void gc_promote_to_shared(void* object);

// ============================================================================
// 垃圾回收函数
// ============================================================================

// 强制执行完整的垃圾回收（触发最高代 GC）
void gc_collect(void);

// 执行指定代的垃圾回收
// generation: 0 (年轻代), 1 (中年代), 2 (老年代)
void gc_collect_generation(int generation);

// Python 风格的循环引用检测（引用计数差值法）
void gc_detect_cycles(void);

// ============================================================================
// 统计和调试
// ============================================================================

// 打印 GC 统计信息
void gc_print_stats(void);

// 清理所有对象（程序退出时自动调用）
void gc_cleanup(void);

// ============================================================================
// 设计说明
// ============================================================================
//
// Dream GC 系统的核心特性：
//
// 1. 双模式引用计数：
//    - 局部对象（SCOPE_LOCAL）：非原子引用计数，性能接近无 GC
//    - 共享对象（SCOPE_SHARED）：原子引用计数，保证线程安全
//
// 2. Python 风格循环引用检测：
//    - 只对容器对象（DYNARRAY, DICT, TUPLE）使用引用计数差值法
//    - 非容器对象简单使用引用计数，无额外开销
//
// 3. 三代分代 GC：
//    - Gen 0 (年轻代): 阈值 700，频繁 GC
//    - Gen 1 (中年代): 阈值 10
//    - Gen 2 (老年代): 阈值 10，完整 GC
//
// 4. 性能特点：
//    - 局部对象操作：0 原子操作（纯非原子）
//    - 共享对象操作：~20 周期（原子操作）
//    - 循环引用检测：O(容器对象数量)，非 STW
//    - GC 停顿：1-10ms（取决于容器数量）
//
// 5. 并发支持：
//    - 全局对象链表：使用互斥锁保护
//    - 容器对象链表：使用互斥锁保护
//    - 内存池：每个池一把锁，减少锁竞争
//    - 统计信息：使用原子变量
//
// ============================================================================

#endif // DREAM_MEMORY_H
